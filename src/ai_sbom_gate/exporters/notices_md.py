"""Generates a ready-to-commit THIRD_PARTY_NOTICES.md from discovered AI & code assets."""

from __future__ import annotations

from ai_sbom_gate.catalog.spdx_licenses import resolve_license_profile
from ai_sbom_gate.models import AssetType, ComplianceReport


def render_third_party_notices(report: ComplianceReport) -> str:
    """Render THIRD_PARTY_NOTICES.md grouped by code packages, models, and datasets."""
    lines: list[str] = [
        "# Third-Party Notices & AI Asset Attributions",
        "",
        f"Generated by `ai-sbom-gate` for `{report.target}` (Policy: `{report.policy.value}`).",
        "",
        "> **Disclaimer**: This file summarizes discovered third-party software packages, models, "
        "and datasets and does not constitute formal legal advice.",
        "",
    ]

    groups = [
        ("Python Packages", AssetType.PYTHON_PACKAGE),
        ("Node.js Packages", AssetType.NODE_PACKAGE),
        ("Hugging Face Models", AssetType.HF_MODEL),
        ("Datasets", AssetType.HF_DATASET),
    ]

    for heading, atype in groups:
        items = [a for a in report.assets if a.asset_type == atype]
        if not items:
            continue
        lines.append(f"## {heading} ({len(items)})")
        lines.append("")
        lines.append("| Asset | Version | License | Category | Source |")
        lines.append("| :--- | :--- | :--- | :--- | :--- |")
        seen: set[tuple[str, str]] = set()
        for a in sorted(items, key=lambda x: x.name.lower()):
            key = (a.name.lower(), a.normalized_license)
            if key in seen:
                continue
            seen.add(key)
            prof = resolve_license_profile(a.normalized_license)
            link_name = f"[{a.name}]({a.homepage})" if a.homepage else a.name
            lic_label = f"[{prof.spdx_id}]({prof.url})" if prof.url else prof.spdx_id
            lines.append(
                f"| {link_name} | `{a.version or '-'}` | {lic_label} | `{a.license_category.value}` | `{a.source_file}` |"
            )
        lines.append("")

    if not report.assets:
        lines.append("No third-party dependencies, models, or datasets were detected.")
        lines.append("")

    return "\n".join(lines)
